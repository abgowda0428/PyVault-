# length function for string 
print(len(full_name))

# indexing
print(full_name[1]) # forward indexing

print(full_name[-9]) # reverse indexing

# slicing 
print(full_name[0:3]) # forward slicing

print(full_name[-5:-1]) # reverse slicing

